const APP_THEME_IDS = new Set(APP_THEMES.map((theme) => theme.id));

export function normalizeAppThemeId(value: unknown): AppThemeId {
    return APP_THEME_IDS.has(value as AppThemeId) ? value as AppThemeId : 'default';
}

export function applyAppTheme(themeId: AppThemeId, root: HTMLElement = document.documentElement) {
    const theme = APP_THEMES.find((item) => item.id === themeId) || APP_THEMES[0];
    Object.entries(theme.tokens).forEach(([key, value]) => root.style.setProperty(key, value));
    root.style.colorScheme = theme.colorScheme;
    if (theme.id === 'default') {
        delete root.dataset.theme;
    } else {
        root.dataset.theme = theme.id;
    }
}
